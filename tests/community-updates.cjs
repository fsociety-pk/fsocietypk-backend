// Real MongoDB + controllers + routers, isolated disposable database; no external services.
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const jwt = require('jsonwebtoken');
const database = `fsocietypk_community_test_${Date.now()}_${process.pid}`;
Object.assign(process.env, { NODE_ENV: 'test', MONGODB_URI: `mongodb://127.0.0.1:27017/${database}`, JWT_SECRET: 'community-tests-secret-never-use-in-production', R2_ACCOUNT_ID: 'test', R2_ACCESS_KEY_ID: 'test', R2_SECRET_ACCESS_KEY: 'test', R2_BUCKET: 'test', LOG_LEVEL: 'error' });
const { User } = require('../dist/models/User');
const { Challenge } = require('../dist/models/Challenge');
const { Submission } = require('../dist/models/Submission');
const { Writeup } = require('../dist/models/Writeup');
const challengeController = require('../dist/controllers/challenge.controller');
const writeups = require('../dist/controllers/writeup.controller');
const admins = require('../dist/controllers/admin.controller');
const adminRouter = require('../dist/routes/admin.routes').default;
const writeupRouter = require('../dist/routes/writeup.routes').default;
const events = [];
const socket = require('../dist/socket');
socket.emitLeaderboardUpdate = () => events.push('leaderboardUpdate');
socket.emitWriteupsUpdate = () => events.push('writeupsUpdate');
const { encryptFlags, decryptFlags } = require('../dist/utils/flagVault');
const invoke = (handler, request = {}) => new Promise((resolve, reject) => handler({ body: {}, params: {}, query: {}, ...request }, { status() { return this; }, json: body => resolve(body.data) }, reject));
const route = (router, method, url, user, body = {}) => new Promise((resolve, reject) => {
  const token = user ? jwt.sign({ userId: user.id, role: 'admin', sessionVersion: 0 }, process.env.JWT_SECRET) : '';
  const req = { method, url, originalUrl: url, baseUrl: '', headers: token ? { authorization: `Bearer ${token}` } : {}, cookies: {}, body, query: {}, params: {} };
  const res = { status(code) { this.statusCode = code; return this; }, json(body) { resolve({ status: this.statusCode || 200, body }); }, setHeader() {}, getHeader() {}, end() { resolve({ status: this.statusCode || 200 }); } };
  router.handle(req, res, error => error ? resolve({ status: error.statusCode, error }) : reject(new Error(`Unhandled route ${method} ${url}`)));
});
let connected = false;
async function run() {
  await mongoose.connect(process.env.MONGODB_URI, { serverSelectionTimeoutMS: 3000 }); connected = true;
  await Promise.all([User.init(), Challenge.init(), Submission.init(), Writeup.init()]);
  const member = await User.create({ username: 'guide_author', password: 'TestPass123!' });
  const other = await User.create({ username: 'other_solver', password: 'TestPass123!' });
  const admin = await User.create({ username: 'guide_admin', password: 'TestPass123!', role: 'admin' });
  const makeChallenge = (title, extra) => Challenge.create({ title, description: 'Disposable community regression fixture', category: 'web', difficulty: 'easy', status: 'approved', isActive: true, createdBy: admin._id, ...extra });
  const single = await makeChallenge('Single vault test', { flag: 'fsociety{single_test}' });
  const multi = await makeChallenge('Multi vault test', { flags: [{ sequence: 1, value: 'fsociety{first}' }, { sequence: 2, value: 'fsociety{second}' }] });
  assert(single.encryptedFlagValues && !single.encryptedFlagValues.includes('single_test'));
  assert.equal(single.toObject().encryptedFlagValues, undefined);
  assert.equal(single.toJSON().encryptedFlagValues, undefined);
  assert.equal((await Challenge.findById(single.id)).encryptedFlagValues, undefined);
  assert.notEqual(encryptFlags([{ sequence: 1, value: 'test' }]), encryptFlags([{ sequence: 1, value: 'test' }]));
  const payload = encryptFlags([{ sequence: 1, value: 'test' }]);
  assert.equal(decryptFlags(payload)[0].value, 'test');
  const pieces = payload.split('.'); const bytes = Buffer.from(pieces[3], 'base64'); bytes[0] ^= 1; pieces[3] = bytes.toString('base64');
  assert.throws(() => decryptFlags(pieces.join('.')));
  for (const challenge of [single, multi]) {
    assert.equal((await route(adminRouter, 'GET', `/challenges/${challenge.id}/flags`)).status, 401);
    assert.equal((await route(adminRouter, 'GET', `/challenges/${challenge.id}/flags`, member)).status, 403);
    assert.equal((await route(adminRouter, 'PUT', `/challenges/${challenge.id}/flags`, member, { flags: ['x'] })).status, 403);
    const revealed = await route(adminRouter, 'GET', `/challenges/${challenge.id}/flags`, admin);
    assert.equal(revealed.status, 200); assert.equal(revealed.body.data.recoverable, true);
    assert.equal(revealed.body.data.flags.length, challenge === multi ? 2 : 1);
  }
  const replacement = await makeChallenge('Replacement flag vault', { flag: 'fsociety{original}' });
  assert.equal((await route(adminRouter, 'PATCH', `/challenges/${replacement.id}`, admin, { flags: [{ sequence: 1, value: 'fsociety{replacement}' }] })).status, 200);
  assert.equal((await route(adminRouter, 'GET', `/challenges/${replacement.id}/flags`, admin)).body.data.flags[0].value, 'fsociety{replacement}');
  console.log('PASS encrypted flags: random IV, tamper rejection, hidden serialization and role-protected readable values');
  const request = { user: { _id: member.id, role: 'user' } };
  const submit = (challenge, flag) => invoke(challengeController.submitFlag, { ...request, body: { challengeId: challenge.id, flag } });
  await submit(multi, 'fsociety{first}');
  assert.equal((await invoke(challengeController.getRecentActivity)).length, 0);
  assert.equal(events.length, 0, 'partial flags do not announce a full solve');
  await submit(single, 'fsociety{single_test}');
  await Submission.updateOne({ userId: member._id, challengeId: single._id }, { timestamp: new Date('2026-10-26T10:00:00Z') });
  await submit(multi, 'fsociety{second}');
  await Submission.updateOne({ userId: member._id, challengeId: multi._id, sequenceNumber: 2 }, { timestamp: new Date('2026-10-27T10:00:00Z') });
  await Submission.updateOne({ userId: member._id, challengeId: multi._id, sequenceNumber: 1 }, { timestamp: new Date('2026-10-25T10:00:00Z') });
  assert.equal(events.filter(event => event === 'leaderboardUpdate').length, 2, 'each full completion broadcasts a live refresh');
  const activity = await invoke(challengeController.getRecentActivity);
  assert.deepEqual(activity.map(item => item.challengeTitle), [multi.title, single.title]);
  assert(activity.every(item => item.username === member.username && item.points === 50));
  assert.equal(new Date(activity[0].timestamp).toISOString(), '2026-10-27T10:00:00.000Z');
  assert(!JSON.stringify(activity).includes('fsociety{'));
  console.log('PASS feed contains full completions only, distinct user/challenge IDs and newest-first completion timestamps');
  // Legacy recovery verifies the existing originals even after solves; comparison hashes do not change.
  await Challenge.updateOne({ _id: multi._id }, { $unset: { encryptedFlagValues: 1 } });
  const before = await Challenge.findById(multi.id).select('+flags');
  assert.equal((await route(adminRouter, 'GET', `/challenges/${multi.id}/flags`, admin)).body.data.recoverable, false);
  assert.equal((await route(adminRouter, 'PUT', `/challenges/${multi.id}/flags`, admin, { flags: ['wrong', 'wrong'] })).status, 400);
  assert.equal((await route(adminRouter, 'PUT', `/challenges/${multi.id}/flags`, admin, { flags: ['fsociety{first}', 'fsociety{second}'] })).status, 200);
  assert.deepEqual((await Challenge.findById(multi.id).select('+flags')).flags.map(f => f.value), before.flags.map(f => f.value));
  assert.equal((await route(adminRouter, 'GET', `/challenges/${multi.id}/flags`, admin)).body.data.flags[1].value, 'fsociety{second}');
  assert.equal((await User.findById(member.id)).score, 100);
  console.log('PASS legacy recovery rejects wrong originals and preserves existing hashes, solves and points');
  const writeup = await Writeup.create({ userId: member._id, challengeId: single._id, title: 'An approved walkthrough', content: 'A complete explanation of the investigation and the final solution.'.repeat(2) });
  const rejected = await Writeup.create({ userId: other._id, challengeId: single._id, title: 'A rejected walkthrough', content: 'This rejected guide should never appear in community results.'.repeat(2), status: 'rejected', adminNotes: 'Private feedback' });
  assert.equal((await invoke(writeups.getApprovedWriteups)).writeups.length, 0);
  assert.equal((await route(writeupRouter, 'GET', `/${writeup.id}`)).status, 403);
  assert.equal((await route(writeupRouter, 'GET', `/${writeup.id}`, other)).status, 403);
  assert.equal((await route(writeupRouter, 'GET', `/${writeup.id}`, member)).status, 200);
  assert.equal((await route(writeupRouter, 'GET', `/${writeup.id}`, admin)).status, 200);
  assert.equal((await route(writeupRouter, 'PUT', `/${writeup.id}/approve`, other)).status, 403);
  assert.equal((await route(writeupRouter, 'PUT', `/${writeup.id}/approve`, admin)).status, 200);
  assert.equal(events.filter(event => event === 'writeupsUpdate').length, 1, 'approval broadcasts community cache invalidation');
  const library = await route(writeupRouter, 'GET', '/');
  assert.equal(library.body.data.writeups.length, 1);
  assert.equal(library.body.data.writeups[0].userId.username, member.username);
  assert.equal((await invoke(writeups.getUserWriteups, request)).writeups[0].userId.username, member.username);
  const publicDetail = await route(writeupRouter, 'GET', `/${writeup.id}`);
  assert.equal(publicDetail.status, 200); assert.equal(publicDetail.body.data.challengeId._id.toString(), single.id);
  assert.equal(publicDetail.body.data.adminNotes, undefined);
  assert.equal((await route(writeupRouter, 'GET', `/${rejected.id}`)).status, 403);
  let cards = await invoke(challengeController.getChallenges, request);
  assert.equal(cards.find(c => c._id.toString() === single.id).writeupCount, 1);
  assert.equal((await invoke(challengeController.getChallengeById, { ...request, params: { id: single.id } })).writeupCount, 1);
  for (const card of cards) { assert.equal(card.flags, undefined); assert.equal(card.flag, undefined); assert.equal(card.encryptedFlagValues, undefined); }
  await route(writeupRouter, 'PUT', `/${writeup.id}/reject`, admin, { adminNotes: 'Needs edits' });
  assert.equal(events.filter(event => event === 'writeupsUpdate').length, 2, 'revocation broadcasts community cache invalidation');
  assert.equal((await invoke(writeups.getApprovedWriteups)).writeups.length, 0);
  cards = await invoke(challengeController.getChallenges, request);
  assert.equal(cards.find(c => c._id.toString() === single.id).writeupCount, 0);
  console.log('PASS approval publishes author-attributed guides and challenge counts; pending/rejected guides stay private; revocation removes availability');
  // Deleted authors must never bypass pending-writeup access checks.
  await User.deleteOne({ _id: other._id });
  assert.equal((await route(writeupRouter, 'GET', `/${rejected.id}`)).status, 403);
  console.log('All community integration checks passed against an isolated MongoDB database.');
}
run().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { if (connected) await mongoose.connection.dropDatabase(); await mongoose.disconnect(); });
