// Real profile projection/controllers and schemas with isolated model doubles.
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
Object.assign(process.env, { NODE_ENV: 'test', MONGODB_URI: 'mongodb://localhost/unused_badge_test', JWT_SECRET: 'badge-tests-secret-never-use-in-production', R2_ACCOUNT_ID: 'test', R2_ACCESS_KEY_ID: 'test', R2_SECRET_ACCESS_KEY: 'test', R2_BUCKET: 'test', LOG_LEVEL: 'error' });
const { profileSolveData } = require('../dist/utils/challengeProgress');
const { User } = require('../dist/models/User');
const { Submission } = require('../dist/models/Submission');
const { Challenge } = require('../dist/models/Challenge');
const controllers = require('../dist/controllers/user.controller');
const { updateUserProfileSchema } = require('../dist/validators/auth.validator');
const userId = new mongoose.Types.ObjectId(), otherId = new mongoose.Types.ObjectId();
const categories = ['web', 'crypto', 'pwn', 'rev', 'forensics', 'osint', 'stego', 'network', 'mobile', 'misc'];
const complete = index => ({ _id: { userId, challengeId: new mongoose.Types.ObjectId() }, challenge: { _id: new mongoose.Types.ObjectId(), title: `Completed challenge ${index}`, category: categories[index % 10], difficulty: 'hard', points: 250, status: 'approved' }, isSolved: true, completedFlags: 5, totalFlags: 5, completedSequences: [1, 2, 3, 4, 5], pointsAwarded: 200, completedAt: new Date(Date.UTC(2026, 9, index + 1)), timestamp: new Date(Date.UTC(2026, 9, index + 1)) });
const completions = Array.from({ length: 27 }, (_, index) => complete(index));
const partial = { ...complete(28), isSolved: false, completedFlags: 4, completedAt: null, pointsAwarded: 0 };
const rows = [...completions, partial];
const invoke = (handler, request = {}) => new Promise((resolve, reject) => handler({ body: {}, params: {}, query: {}, ...request }, { status() { return this; }, json: body => resolve(body.data) }, reject));
async function run() {
  const awards = profileSolveData(rows);
  assert.equal(awards.solveHistory.length, 20);
  assert.equal(awards.earnedBadges.length, 27, 'old awards are not truncated with recent history');
  assert.equal(awards.earnedBadges.some(badge => badge.challengeId === partial.challenge._id.toString()), false);
  assert.equal(new Set(awards.earnedBadges.map(badge => badge.id)).size, 27);
  assert.equal(new Set(awards.earnedBadges.map(badge => badge.category)).size, 10);
  const newest = awards.earnedBadges[0];
  assert.equal(newest.title, completions.at(-1).challenge.title);
  assert.equal(newest.earnedAt.toISOString(), completions.at(-1).completedAt.toISOString());
  assert.equal(newest.points, 200, 'uses points actually earned, rather than current challenge points');
  assert.equal(newest.difficulty, 'hard');
  assert.equal(newest.id, `${userId}:${newest.challengeId}`);
  assert.deepEqual(profileSolveData(rows).earnedBadges, awards.earnedBadges, 'reloading produces the same earned collection');
  assert.deepEqual(profileSolveData([partial]).earnedBadges, []);
  assert(!updateUserProfileSchema.safeParse({ earnedBadges: [newest] }).success, 'clients cannot mint badges through profile edits');
  assert(!JSON.stringify(awards.earnedBadges).includes('completedSequences'));
  console.log('PASS full-completion awards, ten categories, actual points/date, stable IDs, complete history, partial exclusion and no client minting');
  let publicProfile = true;
  const stored = { _id: userId, username: 'badge_owner', role: 'user', score: 5400, isProfilePublic: true, toObject() { return { _id: userId, username: this.username, score: this.score, isProfilePublic: publicProfile }; } };
  User.findById = async () => stored;
  User.findOne = async () => ({ ...stored, isProfilePublic: publicProfile });
  User.countDocuments = async () => 0;
  Submission.aggregate = async pipeline => pipeline[0].$match.userId.toString() === userId.toString() ? rows : [];
  Challenge.aggregate = async () => categories.map(category => ({ _id: category, total: 10 }));
  const own = await invoke(controllers.getProfile, { user: { _id: userId.toString() } });
  assert.equal(own.earnedBadges.length, 27);
  const another = await invoke(controllers.getProfile, { user: { _id: otherId.toString() } });
  assert.equal(another.earnedBadges.length, 0, 'an account cannot inherit another user’s awards');
  const shared = await invoke(controllers.getPublicProfile, { params: { username: stored.username } });
  assert.deepEqual(shared.earnedBadges, own.earnedBadges);
  publicProfile = false;
  await assert.rejects(invoke(controllers.getPublicProfile, { params: { username: stored.username } }), error => error.statusCode === 403);
  assert.equal((await invoke(controllers.getProfile, { user: { _id: userId.toString() } })).earnedBadges.length, 27);
  console.log('PASS private/public profile collections, stored-account ownership and existing visibility rules');
}
run().catch(error => { console.error(error); process.exitCode = 1; });
